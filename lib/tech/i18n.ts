export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, es };

/** Looks a key up in the locale, falls back to English, and fills {vars}. */
export function t(locale: Locale | string, key: MessageKey | string, vars: Record<string, string | number> = {}): string {
  const table = MESSAGES[(locale as Locale) in MESSAGES ? (locale as Locale) : "en"];
  const template = (table as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** The gap message for a gap key: known keys have their own text, pack keys use the generic one. */
export function gapMessage(locale: Locale | string, gapKey: string): string {
  const known = `gap.${gapKey}`;
  return known in en ? t(locale, known) : t(locale, "gap.field", { field: gapKey });
}
