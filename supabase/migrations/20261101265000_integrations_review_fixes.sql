-- Spec 20 review fixes: an atomic API rate limit, webhooks in order across runs and only to public https hosts, a
-- delivery that a 410 ends marked failed, retention on every run, the office's duplicate rule for API leads, weekend
-- availability where the company works weekends, accounts checked by the visit and invoice reads, phone numbers without
-- digits matching nobody, and composite foreign keys. Committed migrations are not edited; these replace functions.

-- ---------------------------------------------------------------------------
-- The API's rate limit (rule 2): one call at a time per key reserves its place, so a burst cannot pass together.
-- ---------------------------------------------------------------------------

alter table public.api_requests drop constraint if exists api_requests_status_check;
alter table public.api_requests add constraint api_requests_status_check check (status between 0 and 599);

create or replace function app.api_begin(p_prefix text, p_hash text, p_method text, p_path text)
returns table (request_id uuid, key_id uuid, tenant_id uuid, scopes text[], limited boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  k record;
  v_used integer;
  v_id uuid;
begin
  select ak.id, ak.tenant_id, ak.scopes into k from public.api_keys ak join public.tenants t on t.id = ak.tenant_id
  where ak.prefix = p_prefix and ak.key_hash = p_hash and ak.revoked_at is null and t.status = 'active';
  if k.id is null then return; end if;
  perform pg_advisory_xact_lock(hashtext('api:' || k.id::text));
  -- Refused calls (429) do not count: a tool that ignores Retry-After does not lock out the others sharing the key.
  select count(*) into v_used from public.api_requests r where r.api_key_id = k.id and r.at > now() - interval '1 minute' and r.status <> 429;
  insert into public.api_requests (tenant_id, api_key_id, method, path, status)
  values (k.tenant_id, k.id, left(p_method, 10), left(p_path, 200), case when v_used >= 60 then 429 else 0 end)
  returning id into v_id;
  update public.api_keys set last_used_at = now() where id = k.id;
  return query select v_id, k.id, k.tenant_id, k.scopes, v_used >= 60;
end $$;

create or replace function app.api_finish(p_request uuid, p_status integer) returns void
language sql security definer set search_path = public, pg_temp as $$
  update public.api_requests set status = p_status where id = p_request and status = 0;
$$;

